const puppeteer = require('puppeteer');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
(async () => {
  const root=path.resolve('dist');
  const server=http.createServer((req,res)=>{
    let file=path.resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));
    if(!file.startsWith(root+path.sep)){res.writeHead(403).end();return;}
    if(fs.existsSync(file)&&fs.statSync(file).isDirectory()) file=path.join(file,'index.html');
    if(!fs.existsSync(file)) file=path.join(root,'index.html');
    const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.webp':'image/webp','.png':'image/png','.svg':'image/svg+xml'};
    res.setHeader('Content-Type',types[path.extname(file)]||'application/octet-stream');fs.createReadStream(file).pipe(res);
  });
  await new Promise(resolve=>server.listen(4173,'127.0.0.1',resolve));
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  fs.mkdirSync('docs/catalog-expansion/screenshots', { recursive: true });
  await page.setViewport({width:1440,height:1000});
  await page.goto('http://127.0.0.1:4173/pneus', {waitUntil:'networkidle2'});
  await page.waitForSelector('.consultation-explorer');
  assert.equal(await page.$$eval('.consultation-electric [data-model]', nodes=>nodes.length),5);
  await page.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo({top:document.querySelector('.consultation-grid').getBoundingClientRect().top+window.scrollY-110,behavior:'instant'});});
  await page.waitFor(250);
  await page.screenshot({path:'docs/catalog-expansion/screenshots/desktop.png'});
  const brandSelect = await page.$eval('label[for="catalog-brand"]', el=>el.htmlFor).catch(()=>null);
  assert(brandSelect, 'Brand control exists');
  await page.select('#'+brandSelect,'MICHELIN');
  assert.equal(await page.$$eval('.consultation-explorer [data-model]',nodes=>nodes.length),3);
  await page.select('#'+brandSelect,'XBRI');
  assert.equal(await page.$$eval('.consultation-explorer [data-model]',nodes=>nodes.length),3);
  assert(await page.$eval('.consultation-more',el=>el.open));
  await page.setViewport({width:390,height:844});
  await page.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo({top:document.querySelector('.consultation-grid').getBoundingClientRect().top+window.scrollY-110,behavior:'instant'});});
  await page.waitFor(250);
  await page.screenshot({path:'docs/catalog-expansion/screenshots/mobile-brand.png'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal overflow');
  const link=await page.$eval('.consultation-cta',el=>el.href);
  assert(link.includes('phone=554130827282') && decodeURIComponent(link).includes('SPORTLINE C2'));
  await page.goto('http://127.0.0.1:4173/pneus-eletricos-curitiba', {waitUntil:'networkidle2'});
  assert.equal(await page.$$eval('.consultation-electric [data-model]',nodes=>nodes.length),5);
  await page.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo({top:document.querySelector('.consultation-grid').getBoundingClientRect().top+window.scrollY-110,behavior:'instant'});});
  await page.waitFor(250);
  await page.screenshot({path:'docs/catalog-expansion/screenshots/mobile-electric.png'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  console.log('PASS: browser desktop/mobile, brand filters, 5 EV lines, WhatsApp target, no overflow or JS errors.');
  await browser.close();
  server.close();
})().catch(error=>{console.error(error);process.exit(1)});
